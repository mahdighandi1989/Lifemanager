def rd(p):
    with open(p, encoding="utf-8") as f:
        return f.read()


def h10(s):
    return hashlib.sha256(s.encode("utf-8")).hexdigest()[:10]


def ledger_js():
    """The continuous backtest's own record (backtest/*.json, written by tools/epi_backtest.js) — embedded so the page
    shows rounds, findings and per-event verdicts. Absent files ⇒ an empty ledger (the page says «not run yet»)."""
    bt = os.path.join(B, "backtest")
    def j(n, d):
        p = os.path.join(bt, n)
        return json.loads(rd(p)) if os.path.exists(p) else d
    data = {"ledger": j("ledger.json", {"rounds": []}), "findings": j("findings.json", {"findings": []}), "results": j("results.json", {"cases": []}),
            "proposals": j("proposals.json", {"proposals": []}), "foundation": j("foundation.json", None), "territory": j("territory.json", {"areas": {}})}
    fnd = data["foundation"] or {}
    data["baseval"] = {k: v.get("p") for k, v in (fnd.get("base") or {}).items()}   # مقدارهای پایهٔ سنجیده ⇒ همان سقف‌های موتورِ Node
    # «چه کسی مالکِ چیست» (docs/supervisor/ownership.json) — همان نقشه‌ای که روتین‌ها از آن پیروی می‌کنند؛ «💬 دستیار» با آن
    # هر کمبود را به قلمرو و روتینِ درست می‌فرستد (فقط قلمروهای همین صفحه + نام و آهنگِ روتین‌ها؛ بی مسیرِ فایل). تغییرِ آن ⇒ build.py.
    op = os.path.join(os.path.dirname(os.path.dirname(B)), "docs", "supervisor", "ownership.json")
    if os.path.exists(op):
        own = json.loads(rd(op))
        data["ownership"] = {"routines": {k: {"fa": v.get("fa"), "cadence": v.get("cadence"), "prompt": v.get("prompt"),
                                              "agenda": [x.get("what") for x in v.get("agenda", [])]} for k, v in own.get("routines", {}).items()},
                             "areas": [{k: a.get(k) for k in ("id", "fa", "owner", "executor", "procedure", "rule")} for a in own.get("areas", []) if a.get("page")]}
    return "window.EPI_BT_LEDGER = " + json.dumps(data, ensure_ascii=False, sort_keys=True, separators=(",", ":")) + ";\n"


def systerr_js():
    """«🗺 قلمروِ سامانه‌ها» (territory/maps/*.json + territory/ledger.json — tools/sys_territory.py) ⇒ پیش از کدِ صفحه."""
    td = os.path.join(B, "territory")
    maps = []
    for p in sorted(glob.glob(os.path.join(td, "maps", "*.json"))):
        maps.append(json.loads(rd(p)))
    lp = os.path.join(td, "ledger.json")
    led = json.loads(rd(lp)) if os.path.exists(lp) else {"areas": {}}
    return ("window.SYS_TERR = " + json.dumps({"systems": maps}, ensure_ascii=False, sort_keys=True, separators=(",", ":")) + ";\n" +
            "window.SYS_TERR_LEDGER = " + json.dumps(led, ensure_ascii=False, sort_keys=True, separators=(",", ":")) + ";\n")


def sources_js():
    """«📚 منبع‌ها و پوشش»: هر کتاب/منبعِ بیرونی که مالک می‌فرستد (sources/<id>/source.json + items.json + coverage.json) ⇒ پیش از کدِ صفحه."""
    out = []
    for d in sorted(glob.glob(os.path.join(B, "sources", "*", "source.json"))):
        base = os.path.dirname(d)
        meta = json.loads(rd(d))
        meta["items"] = json.loads(rd(os.path.join(base, "items.json")))
        cp = os.path.join(base, "coverage.json")
        meta["coverage"] = json.loads(rd(cp)) if os.path.exists(cp) else {"verdicts": {}, "beyond": []}
        out.append(meta)
    return "window.SRC_COV = " + json.dumps(out, ensure_ascii=False, sort_keys=True, separators=(",", ":")) + ";\n"


def copy_norm_images():
    """تصویرهای معماهای لنگردار (norms/img) ⇒ کنارِ بسته (public/assets/lla/norms/img) و کنارِ فایلِ مستقل (dist/norms/img)."""
    src = os.path.join(B, "norms", "img")
    for dst in (os.path.join(ASSETS, "norms", "img"), os.path.join(D, "norms", "img")):
        os.makedirs(dst, exist_ok=True)
        keep = set(os.listdir(src)) if os.path.isdir(src) else set()
        for f in os.listdir(dst):
            if f not in keep:
                os.remove(os.path.join(dst, f))
        for f in keep:
            shutil.copyfile(os.path.join(src, f), os.path.join(dst, f))


def norms_js():
    """«📐 سنجشِ استاندارد»: گویه‌های لنگردار با دشواریِ جمعیتی از منبعِ معتبر (norms/norms.json) ⇒ پیش از کدِ صفحه."""
    p = os.path.join(B, "norms", "norms.json")
    d = json.loads(rd(p)) if os.path.exists(p) else {"items": [], "sources": []}
    return "window.PSY_NORMS = " + json.dumps(d, ensure_ascii=False, sort_keys=True, separators=(",", ":")) + ";\n"


