"""Handbook machinery for «معماری یادگیری عمیق و کارخانهٔ معرفت‌شناسی».

One parser, used by three consumers so they can never disagree:
  * build.py      — regenerates the progress chart inside HANDBOOK.md and writes
                    progress.json for the in-app chart;
  * build.py --check and tests/test_learning_architecture_handbook.py — the merge gate;
  * (indirectly) the page, which only ever reads what build.py produced.

Rules it enforces (see HANDBOOK.md §13 for the human version):
  * PROGRESS.md has the exact header below; rows numbered 1..N with no gaps, dates
    non-decreasing, direction made only of ▲ ▼ ↩ ●, metrics numeric or «–», and every
    row cites at least one existing WORKLOG entry — no chart point without evidence;
  * every WORKLOG entry heading is «## YYYY-MM-DD (n) — title», n = 1..N, and every
    entry ends with a signature line;
  * every in-page link (#anchor) resolves to a heading (GitHub's slug rules, mirrored in
    the frontend);
  * the table of contents and the chart block between their markers equal what
    render_toc() / render_chart() produce (both are generated, never hand-edited);
  * the «به‌روزرسانی:» date is not older than the newest ledger row.
"""
import json
import re
import unicodedata

PROGRESS_HEADER = ["#", "تاریخ", "رویداد", "جهت", "تکنیک", "ایستگاه", "قاعده", "پرونده", "آزمون ۱", "آزمون ۲", "سند"]
METRICS = ["تکنیک", "ایستگاه", "قاعده", "پرونده", "آزمون ۱", "آزمون ۲"]
METRIC_KEYS = ["techniques", "stations", "rules", "cases", "test1", "test2"]
DIR_SCORE = {"▲": 1, "▼": -1, "↩": 1, "●": 0}
CHART_BEGIN = "<!-- PROGRESS-CHART:BEGIN (generated by apps/learning-architecture/build.py — do not edit by hand) -->"
CHART_END = "<!-- PROGRESS-CHART:END -->"
TOC_BEGIN = "<!-- TOC:BEGIN (generated by apps/learning-architecture/build.py from the ## headings) -->"
TOC_END = "<!-- TOC:END -->"
WORKLOG_HEAD = re.compile(r"^## (\d{4}-\d{2}-\d{2}) \((\d+)\) — (.+)$")
SIGNATURE = re.compile(r"^>\s*\*\*امضا:\*\*\s*`[^`]+`\s*·\s*\d{4}-\d{2}-\d{2}\s*·\s*\S")
FA_DIGITS = str.maketrans("۰۱۲۳۴۵۶۷۸۹", "0123456789")


def _cells(line):
    return [c.strip() for c in line.strip().strip("|").split("|")]


def parse_progress(text):
    """Return (rows, problems). A row is a dict; metrics are float|None (None = unchanged)."""
    problems, rows, header_seen = [], [], False
    for ln, line in enumerate(text.splitlines(), 1):
        if not line.startswith("|"):
            continue
        cells = _cells(line)
        if cells[0] == "#":
            header_seen = True
            if cells != PROGRESS_HEADER:
                problems.append("PROGRESS.md:%d header must be exactly: | %s |" % (ln, " | ".join(PROGRESS_HEADER)))
            continue
        if set(cells[0]) <= set("-: "):
            continue
        if len(cells) != len(PROGRESS_HEADER):
            problems.append("PROGRESS.md:%d has %d columns, expected %d" % (ln, len(cells), len(PROGRESS_HEADER)))
            continue
        num, date, event, direction = cells[0], cells[1], cells[2], cells[3]
        if not num.isdigit():
            problems.append("PROGRESS.md:%d row number %r is not an integer" % (ln, num))
            continue
        row = {"n": int(num), "date": date, "event": event, "dir": direction, "refs": [], "line": ln}
        if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", date):
            problems.append("PROGRESS.md:%d date %r is not YYYY-MM-DD" % (ln, date))
        if not direction or any(ch not in DIR_SCORE for ch in direction):
            problems.append("PROGRESS.md:%d direction %r must use only ▲ ▼ ↩ ●" % (ln, direction))
        for key, cell in zip(METRIC_KEYS, cells[4:10]):
            if cell in ("–", "-", ""):
                row[key] = None
                continue
            try:
                row[key] = float(cell.translate(FA_DIGITS).replace("٫", "."))
            except ValueError:
                problems.append("PROGRESS.md:%d metric %r is not a number or «–»" % (ln, cell))
                row[key] = None
        refs = [int(x.translate(FA_DIGITS)) for x in re.findall(r"WORKLOG\s*\(([\d۰-۹]+)\)", cells[10])]
        if not refs:
            problems.append("PROGRESS.md:%d cites no WORKLOG (n) entry — a point without evidence is forbidden" % ln)
        row["refs"] = refs
        row["score"] = sum(DIR_SCORE.get(ch, 0) for ch in direction)
        rows.append(row)
    if not header_seen:
        problems.append("PROGRESS.md has no header row")
    for i, r in enumerate(rows, 1):
        if r["n"] != i:
            problems.append("PROGRESS.md:%d row number %d should be %d (1..N, no gaps, no repeats)" % (r["line"], r["n"], i))
            break
    for a, b in zip(rows, rows[1:]):
        if b["date"] < a["date"]:
            problems.append("PROGRESS.md:%d date %s is older than the row above (%s)" % (b["line"], b["date"], a["date"]))
    # state after each event: blank metric = unchanged (forward fill)
    cum, last = 0, {k: None for k in METRIC_KEYS}
    for r in rows:
        cum += r["score"]
        r["cumulative"] = cum
        for k in METRIC_KEYS:
            if r[k] is None:
                r[k] = last[k]
            last[k] = r[k]
    return rows, problems


def parse_worklog(text):
    """Return (entries, problems). entries: {n: {date, title}}."""
    problems, entries, order = [], {}, []
    lines = text.splitlines()
    heads = [(i, WORKLOG_HEAD.match(l)) for i, l in enumerate(lines) if l.startswith("## ")]
    for idx, (i, m) in enumerate(heads):
        if not m:
            problems.append("WORKLOG.md:%d heading must be «## YYYY-MM-DD (n) — title»" % (i + 1))
            continue
        n = int(m.group(2))
        if n in entries:
            problems.append("WORKLOG.md:%d entry number (%d) is used twice" % (i + 1, n))
        entries[n] = {"date": m.group(1), "title": m.group(3)}
        order.append(n)
        end = heads[idx + 1][0] if idx + 1 < len(heads) else len(lines)
        body = [l for l in lines[i + 1:end] if l.strip()]
        if not body or not SIGNATURE.match(body[-1]):
            problems.append("WORKLOG.md:%d entry (%d) does not end with a signature line «> **امضا:** `who` · YYYY-MM-DD · how it was verified»" % (i + 1, n))
    if order != list(range(1, len(order) + 1)):
        problems.append("WORKLOG.md entry numbers must run 1..N in file order (newest at the bottom); got %s" % order)
    return entries, problems


def slug(heading):
    """GitHub's heading anchor (github-slugger), mirrored in frontend/src/lib/llaHandbook.js."""
    t = re.sub(r"`([^`]*)`", r"\1", heading)
    t = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", t)
    t = t.replace("**", "").replace("__", "").strip().lower()
    keep = "".join(ch for ch in t if ch in " -_" or unicodedata.category(ch)[0] in "LMN")
    return keep.replace(" ", "-")


def headings(md):
    """All heading slugs in order (fenced code ignored), duplicates suffixed -1, -2 like GitHub."""
    out, seen, fence = [], {}, False
    for line in md.splitlines():
        if line.lstrip().startswith("```"):
            fence = not fence
            continue
        m = None if fence else re.match(r"^(#{1,6})\s+(.*?)\s*#*\s*$", line)
        if not m:
            continue
        s = slug(m.group(2))
        if s in seen:
            seen[s] += 1
            s = "%s-%d" % (s, seen[s])
        else:
            seen[s] = 0
        out.append(s)
    return out


def check_anchors(md, name="HANDBOOK.md"):
    have = set(headings(md))
    problems = []
    body = re.sub(r"```.*?```", "", md, flags=re.S)
    for target in re.findall(r"\]\(#([^)\s]+)\)", body):
        if target not in have:
            problems.append("%s: link #%s does not match any heading (fix the table of contents)" % (name, target))
    return problems


def _ascii(v):
    return ("%g" % v) if v is not None else "0"


def render_chart(rows):
    """The generated §11 block: two mermaid charts (GitHub renders them) + note."""
    if not rows:
        return CHART_BEGIN + "\n_(دفتر پیشرفت هنوز سطری ندارد)_\n" + CHART_END
    xs = ", ".join('"#%d"' % r["n"] for r in rows)
    lo = min(0, min(r["cumulative"] for r in rows), min(r["score"] for r in rows))
    hi = max(1, max(r["cumulative"] for r in rows))
    cases_hi = max([r["cases"] or 0 for r in rows] + [1])
    parts = [CHART_BEGIN, "",
             "```mermaid", "xychart-beta",
             '    title "Trajectory - bar: this event (up +1, down -1, fix +1), line: running total"',
             "    x-axis [%s]" % xs,
             '    y-axis "score" %d --> %d' % (lo, hi),
             "    bar [%s]" % ", ".join(str(r["score"]) for r in rows),
             "    line [%s]" % ", ".join(str(r["cumulative"]) for r in rows),
             "```", "",
             "```mermaid", "xychart-beta",
             '    title "Library size - line: cases, bar: rules (state after each event)"',
             "    x-axis [%s]" % xs,
             '    y-axis "count" 0 --> %d' % int(cases_hi * 1.1 + 1),
             "    bar [%s]" % ", ".join(_ascii(r["rules"]) for r in rows),
             "    line [%s]" % ", ".join(_ascii(r["cases"]) for r in rows),
             "```", "",
             "> نقطه‌ها = سطرهای [دفتر پیشرفت](PROGRESS.md) (#%d تا #%d). جمعِ جاری الان **%d** است. "
             "این بلوک را دستی ویرایش نکن؛ `python apps/learning-architecture/build.py` آن را از روی دفتر می‌سازد."
             % (rows[0]["n"], rows[-1]["n"], rows[-1]["cumulative"]),
             "", CHART_END]
    return "\n".join(parts)


def render_toc(md):
    """Numbered list of every ## heading (fenced code ignored), linked with GitHub anchors."""
    items, fence, seen = [], False, {}
    for line in md.splitlines():
        if line.lstrip().startswith("```"):
            fence = not fence
            continue
        m = None if fence else re.match(r"^(#{1,6})\s+(.*?)\s*#*\s*$", line)
        if not m:
            continue
        s = slug(m.group(2))
        if s in seen:
            seen[s] += 1
            s = "%s-%d" % (s, seen[s])
        else:
            seen[s] = 0
        if len(m.group(1)) == 2 and m.group(2).strip() != "فهرست":
            items.append("- [%s](#%s)" % (re.sub(r"\s+", " ", m.group(2)).strip(), s))
    return TOC_BEGIN + "\n" + "\n".join(items) + "\n" + TOC_END


def replace_toc(md):
    a, b = md.find(TOC_BEGIN), md.find(TOC_END)
    if a < 0 or b < 0:
        raise ValueError("HANDBOOK.md is missing the table-of-contents markers")
    return md[:a] + render_toc(md) + md[b + len(TOC_END):]


def regenerate(md, rows):
    return replace_toc(replace_chart(md, rows))


def replace_chart(md, rows):
    a, b = md.find(CHART_BEGIN), md.find(CHART_END)
    if a < 0 or b < 0:
        raise ValueError("HANDBOOK.md is missing the progress-chart markers")
    return md[:a] + render_chart(rows) + md[b + len(CHART_END):]


def progress_json(rows, worklog):
    keep = ["n", "date", "event", "dir", "score", "cumulative", "refs"] + METRIC_KEYS
    return json.dumps({"metrics": dict(zip(METRIC_KEYS, METRICS)),
                       "rows": [{k: r[k] for k in keep} for r in rows],
                       "worklog": {str(k): v for k, v in sorted(worklog.items())}},
                      ensure_ascii=False, indent=1, sort_keys=True)


def validate(handbook, progress, worklog_text):
    """All documentation problems as a list of strings (empty = in sync)."""
    rows, problems = parse_progress(progress)
    entries, p2 = parse_worklog(worklog_text)
    problems += p2
    for r in rows:
        for ref in r["refs"]:
            if ref not in entries:
                problems.append("PROGRESS.md:%d cites WORKLOG (%d) which does not exist" % (r["line"], ref))
    problems += check_anchors(handbook)
    try:
        if replace_chart(handbook, rows) != handbook:
            problems.append("HANDBOOK.md progress chart is stale — run: python apps/learning-architecture/build.py")
        if replace_toc(handbook) != handbook:
            problems.append("HANDBOOK.md table of contents is stale — run: python apps/learning-architecture/build.py")
    except ValueError as e:
        problems.append(str(e))
    m = re.search(r"به‌روزرسانی:\s*(\d{4}-\d{2}-\d{2})", handbook)
    if not m:
        problems.append("HANDBOOK.md has no «به‌روزرسانی: YYYY-MM-DD» line")
    elif rows and m.group(1) < rows[-1]["date"]:
        problems.append("HANDBOOK.md «به‌روزرسانی» (%s) is older than the newest PROGRESS row (%s)" % (m.group(1), rows[-1]["date"]))
    if entries and rows:
        newest = max(entries)
        if not any(newest in r["refs"] for r in rows) and entries[newest]["date"] > rows[-1]["date"]:
            problems.append("WORKLOG (%d) is newer than every PROGRESS row — add a row if it moved the page forward/back" % newest)
    return rows, entries, problems
