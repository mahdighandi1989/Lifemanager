def conv(w):
    core=w; pre=''; post=''
    m=re.match(r'^([«(\[]*)(.*?)([»)\].,،؛:!؟?…]*)$',w)
    if m: pre,core,post=m.groups()
    if core in W: return pre+W[core]+post
    m2=re.match('^(ن?می'+Z+'\\S+?)ی$',core)   # present 2sg
    if m2 and len(core)>4: return pre+m2.group(1)+'ید'+post
    if core.endswith(Z+'ات') : return pre+core[:-2]+'تان'+post
    if core.endswith('ه'+Z+'ای') and len(core)>4: return pre+core[:-1]+'ید'+post
    m3=re.match('^(ن?می'+Z+'\\S+?)ی'+Z+'?اش$',core)
    if m3: return pre+m3.group(1)+'یدش'+post
    if core.endswith('هایت'): return pre+core+'ان'+post
    if core.endswith('ات') and core[:-2] in ('مسئله','خانه','نامه','برنامه','پرونده','نتیجه','گوشه','جمله','ایده','کره','نقشه','تجربه','بچه','کارنامه'): return pre+core[:-2]+'‌تان'+post
    return w
def run(t):
    parts=re.split(r'(«[^»]*»)',t)
    return ''.join(p if p.startswith('«') else run0(p) for p in parts)
def run0(t):
    out=[]
    for tok in re.split(r'(\s+)',t):
        out.append(tok if tok.isspace() or not tok else conv(tok))
    return ''.join(out)
if __name__=='__main__': print(run(sys.stdin.read()),end='')
